const SLOT_ORDER: Record<TechSlot, number> = {
  root: 0,
  a: 1,
  b: 2,
  capstone: 3,
};

export function getFactionTechs(faction: FactionId): TechDefinition[] {
  return Object.values(TECH_DEFINITIONS)
    .filter((t) => t.faction === faction)
    .sort((a, b) => a.pillarIndex - b.pillarIndex || a.tier - b.tier || SLOT_ORDER[a.slot] - SLOT_ORDER[b.slot]);
}
